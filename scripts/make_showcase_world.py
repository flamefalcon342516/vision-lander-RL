"""Generate gazebo/worlds/lander_world_showcase.sdf: the evaluation world plus light scenery
(grass, an asphalt pad, a few trees), kept deliberately simple.

Used only with --gui, so measured results (plain world) are unaffected. All scenery is
visual-only (no collision) and placed outside the rover's range (it is recentred past
25 m); the asphalt pad has no grid markings that could look like a marker to the camera.
"""
import math
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
base = (ROOT / "gazebo/worlds/lander_world.sdf").read_text()
rng = random.Random(7)


def mat(r, g, b, spec=0.1, emis=None):
    e = f"<emissive>{emis}</emissive>" if emis else ""
    return (f"<material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse>"
            f"<specular>{spec} {spec} {spec} 1</specular>{e}</material>")


def vis(name, pose, geom, m):
    return f'<visual name="{name}"><pose>{pose}</pose><geometry>{geom}</geometry>{m}</visual>'


def box(sx, sy, sz):
    return f"<box><size>{sx} {sy} {sz}</size></box>"


def cyl(r, l):
    return f"<cylinder><radius>{r}</radius><length>{l}</length></cylinder>"


def sphere(r):
    return f"<sphere><radius>{r}</radius></sphere>"


def model(name, x, y, yaw, visuals):
    return (f'    <model name="{name}"><static>true</static><pose>{x:.2f} {y:.2f} 0 0 0 {yaw:.3f}</pose>'
            f'<link name="link">{"".join(visuals)}</link></model>\n')


GRASS = mat(0.30, 0.47, 0.20, 0.02)
ASPHALT = mat(0.24, 0.24, 0.25, 0.05)
WHITE = mat(0.92, 0.92, 0.90, 0.2)
ORANGE = mat(0.95, 0.42, 0.05, 0.3)

out = []
# ground: grass, plus the asphalt pad the rover drives on
out.append(model("grass", 0, 0, 0, [vis("v", "0 0 0.0005 0 0 0", "<plane><normal>0 0 1</normal><size>300 300</size></plane>", GRASS)]))
pad = [vis("asphalt", "0 0 0.001 0 0 0", "<plane><normal>0 0 1</normal><size>56 56</size></plane>", ASPHALT)]
for i, (x, y, sx, sy) in enumerate([(0, 27.8, 55.6, 0.25), (0, -27.8, 55.6, 0.25), (27.8, 0, 0.25, 55.6), (-27.8, 0, 0.25, 55.6)]):
    pad.append(vis(f"edge{i}", f"{x} {y} 0.0015 0 0 0", f"<plane><normal>0 0 1</normal><size>{sx} {sy}</size></plane>", WHITE))
out.append(model("landing_pad", 0, 0, 0, pad))

# a few trees in a loose ring, 34-55 m out
n = 0
while n < 14:
    r, a = rng.uniform(34, 55), rng.uniform(-math.pi, math.pi)
    x, y = r * math.cos(a), r * math.sin(a)
    h, w = rng.uniform(4, 8), rng.uniform(1.4, 2.4)
    g = rng.uniform(0.75, 1.15)
    leaf = mat(0.16 * g, 0.38 * g, 0.14 * g, 0.05)
    if rng.random() < 0.5:   # conifer
        crown = [vis("c1", f"0 0 {h * 0.45:.2f} 0 0 0", f"<cone><radius>{w}</radius><length>{h * 0.6:.2f}</length></cone>", leaf),
                 vis("c2", f"0 0 {h * 0.75:.2f} 0 0 0", f"<cone><radius>{w * 0.7:.2f}</radius><length>{h * 0.45:.2f}</length></cone>", leaf)]
    else:                    # broadleaf
        crown = [vis("c1", f"0 0 {h * 0.7:.2f} 0 0 0", sphere(w), leaf),
                 vis("c2", f"{w * 0.5:.2f} 0 {h * 0.6:.2f} 0 0 0", sphere(w * 0.7), leaf)]
    out.append(model(f"tree{n}", x, y, rng.uniform(0, 6.28),
                     [vis("trunk", f"0 0 {h * 0.25:.2f} 0 0 0", cyl(0.18, h * 0.5), mat(0.35, 0.24, 0.14))] + crown))
    n += 1

scenery = "\n    <!-- ===== showcase scenery (generated by scripts/make_showcase_world.py) ===== -->\n" + "".join(out)
world = base.replace("  </world>", scenery + "  </world>")
world = world.replace("<ambient>0.6 0.6 0.6 1</ambient>", "<ambient>0.55 0.58 0.62 1</ambient>")
world = world.replace("<background>0.7 0.8 0.9 1</background>", "<background>0.55 0.72 0.92 1</background>")
world = world.replace("      <sky/>\n", "      <sky/>\n      <grid>false</grid>\n")
world = world.replace("Base world for the landing project.",
                      "SHOWCASE copy of lander_world.sdf (GUI only; generated, do not edit).\n  Base world for the landing project.")
dst = ROOT / "gazebo/worlds/lander_world_showcase.sdf"
dst.write_text(world)
print(dst, len(out), "scenery models")
