# Source this in every terminal that works on the project:  source env.sh
# Kept separate from ~/.bashrc so other projects are not affected.
_root="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# gz-transport must bind to loopback: on this machine the default interface
# choice can pick the DOWN docker0 bridge and silently stall data (see the
# SLAM_OMOKAI incident).
export GZ_IP=127.0.0.1

# ardupilot_gazebo plugin (.so) and its models/worlds, plus our own.
export GZ_SIM_SYSTEM_PLUGIN_PATH="$HOME/gz_ws/src/ardupilot_gazebo/build"
export GZ_SIM_RESOURCE_PATH="$_root/gazebo/models:$_root/gazebo/worlds:$HOME/gz_ws/src/ardupilot_gazebo/models:$HOME/gz_ws/src/ardupilot_gazebo/worlds"

# The apt gz-msgs10 Python bindings were generated by an old protoc and are
# rejected by the C/upb protobuf backend that TensorBoard/ONNX require
# (protobuf>=6). The pure-Python backend accepts them; measured cost for a
# 640x480 RGB image parse is ~0.3 ms, so it is negligible for us.
export PROTOCOL_BUFFERS_PYTHON_IMPLEMENTATION=python

# ROS 2 setup.bash puts ROS packages/pytest plugins on PYTHONPATH; the training
# stack does not use ROS, so keep it out of this shell.
unset PYTHONPATH

source "$_root/.venv/bin/activate"
unset _root

# `gz sdf -k` resolves model:// URIs through SDF_PATH, not GZ_SIM_RESOURCE_PATH.
export SDF_PATH="$GZ_SIM_RESOURCE_PATH"
